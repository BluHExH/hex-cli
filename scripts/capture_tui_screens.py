"""Capture HEX CLI OpenCode-style TUI states as Textual SVG screenshots.

Screens: home (empty session), conversation (tool turn), shell turn,
plan mode, medium + narrow sizes. Run: python scripts/capture_tui_screens.py
"""
from __future__ import annotations

import asyncio
from pathlib import Path

from hex_cli.tui.app import HexApp

DOCS = Path(__file__).resolve().parents[1] / "docs" / "screenshots"


async def capture() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    import subprocess
    import tempfile

    tmp = Path(tempfile.mkdtemp(prefix="hex_capture_"))
    (tmp / "src").mkdir()
    (tmp / "src" / "app.py").write_text("import hex\n\nprint('demo')\n", encoding="utf-8")
    (tmp / "README.md").write_text("# Demo workspace\n", encoding="utf-8")
    (tmp / ".hex").mkdir()
    (tmp / ".hex" / "config.json").write_text('{"permission_mode": "allow"}\n', encoding="utf-8")

    # Real git repo so session title / header are exercised with genuine data
    def git(*args: str) -> None:
        subprocess.run(
            ["git", "-c", "user.email=hex-capture@local", "-c", "user.name=HEX Capture", *args],
            cwd=str(tmp), capture_output=True, timeout=15, check=True,
        )

    try:
        git("init", "-b", "main")
        git("add", "-A")
        git("commit", "-m", "capture workspace")
    except (OSError, subprocess.SubprocessError):
        pass

    async def run_turn(app: HexApp, pilot, text: str, settle: float = 0.8) -> None:
        box = app.query_one("#composer-box")
        box.value = text
        await pilot.press("enter")
        for _ in range(60):
            await pilot.pause(0.2)
            if not app._busy:
                break
        await pilot.pause(settle)

    app = HexApp(workspace=tmp)
    async with app.run_test(size=(120, 36)) as pilot:
        await pilot.pause(0.2)
        (DOCS / "ref_match_home_160x45.svg").write_text(app.export_screenshot(), encoding="utf-8")

        await run_turn(app, pilot, "LIST src")
        (DOCS / "ref_match_conversation_160x45.svg").write_text(app.export_screenshot(), encoding="utf-8")

        await run_turn(app, pilot, "WRITE src/demo_generated.py :: # generated by HEX capture\nprint ('generated')\n")
        (DOCS / "ref_match_changes_160x45.svg").write_text(app.export_screenshot(), encoding="utf-8")

    app = HexApp(workspace=tmp)
    async with app.run_test(size=(90, 26)) as pilot:
        await pilot.pause(0.2)
        (DOCS / "ref_match_medium_100x30.svg").write_text(app.export_screenshot(), encoding="utf-8")

    app = HexApp(workspace=tmp)
    async with app.run_test(size=(76, 22)) as pilot:
        await pilot.pause(0.2)
        (DOCS / "ref_match_narrow_80x24.svg").write_text(app.export_screenshot(), encoding="utf-8")

    print("saved:", ", ".join(p.name for p in sorted(DOCS.glob("ref_match_*.svg"))))


if __name__ == "__main__":
    asyncio.run(capture())
